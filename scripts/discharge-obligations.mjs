/** Resolves the two historical corpus env-var names against each other:
 *  whichever is set backfills the other for stages keyed to the "wrong"
 *  name, so a maintainer only has to set one. Both empty strings if
 *  neither is set. */
export function resolveCorpusDirs(env = process.env) {
  const realScriptCorpusDir = env.REAL_SCRIPT_CORPUS_DIR || env.CORPUS_DIR || '';
  const corpusDir = env.CORPUS_DIR || env.REAL_SCRIPT_CORPUS_DIR || '';
  return { realScriptCorpusDir, corpusDir };
}

/** The top-level env-contract gate. Every obligation below needs local
 *  corpus access in some form, so this fails BEFORE any stage runs (not
 *  per-stage) when neither var is set at all. Individual stages may still
 *  report their own skip if only one of the two names ends up unusable
 *  (e.g. set to a path that doesn't exist). */
/** @param {Record<string, string|undefined>} [env]
 *  @returns {{ ok: boolean, message: string }} */
export function checkEnvContract(env = process.env) {
  const hasReal = !!env.REAL_SCRIPT_CORPUS_DIR;
  const hasCorpus = !!env.CORPUS_DIR;
  if (hasReal || hasCorpus) return { ok: true, message: '' };
  return {
    ok: false,
    message: [
      'ERROR: neither REAL_SCRIPT_CORPUS_DIR nor CORPUS_DIR is set.',
      'At least one is required — every obligation below needs local access to the private research corpus.',
      '  REAL_SCRIPT_CORPUS_DIR=/path/to/corpus   (measure-real, truth-extraction recall)',
      '  CORPUS_DIR=/path/to/corpus               (measure-auc-split.mjs flag runs, corpus migration)',
      'Set whichever you have — this script backfills the other name for stages that expect it.',
      'Nothing was run.',
    ].join('\n'),
  };
}

/** Structural guard: the test partition is evaluate-once, never for
 *  iteration (MEASUREMENT_RUNBOOK.md §2.3). This orchestrator's own code
 *  never constructs a --partition=test invocation, but every place a
 *  partition string is about to be used calls this first anyway, so an
 *  edit that accidentally introduces a 'test' partition into the loop
 *  below fails loudly instead of silently shipping a test-partition run. */
export function assertSafePartition(partition) {
  if (partition === 'test') {
    throw new Error(
      "REFUSED: --partition=test must never be invoked from discharge-obligations.mjs. " +
      "The test partition is evaluate-once, final-evaluation-only (MEASUREMENT_RUNBOOK.md §2.3) " +
      "— this orchestrator only ever runs train/val partitions.",
    );
  }
  return partition;
}

/** True iff scripts/output/corpus-split.json is already in the migrated
 *  (de-identified) schema: every entry across train/val/test/excluded
 *  carries `id` + `contentHash`. Mirrors scripts/verify-corpus-layout.mjs's
 *  own isMigrated check exactly, on purpose — two independent
 *  reimplementations of the same rule would drift. */
export function isMigrationApplied(splitData) {
  if (!splitData || typeof splitData !== 'object') return false;
  const partitions = ['train', 'val', 'test', 'excluded'];
  const allEntries = partitions.flatMap((p) => (Array.isArray(splitData[p]) ? splitData[p] : []));
  if (allEntries.length === 0) return false;
  return allEntries.every((e) => typeof e?.id === 'string' && typeof e?.contentHash === 'string');
}

/** Best-effort number extraction from a stage's captured stdout. Returns
 *  the parsed value, or null if the pattern never matched — callers render
 *  null as "see stage log" in the receipt rather than fabricating a
 *  number, per this script's own header contract. */
function extractFirst(text, regex) {
  const m = regex.exec(text ?? '');
  return m ? Number(m[1]) : null;
}

/** Parses scripts/measure-real-script-discrimination.ts's honest-summary
 *  section for the two structural-degradation AUCs it prints there
 *  (shuffle-drop, act-swap — see that script's `console.log` calls in its
 *  "HONEST SUMMARY" block, the cleanest single place both numbers appear
 *  together). */
export function parseMeasureRealOutput(stdout) {
  return {
    shuffleDropAuc: extractFirst(stdout, /shuffle-drop AUC\s+([\d.]+)/),
    actSwapAuc: extractFirst(stdout, /act-swap\s+AUC\s+([\d.]+)/),
  };
}

/** Parses measure-auc-split.mjs's "ALL POOLED" summary row — the single
 *  headline number for a given partition/flag run. */
export function parseAucSplitOutput(stdout) {
  return { allPooledAuc: extractFirst(stdout, /ALL POOLED\s*\|\s*\d+\s*\|\s*([\d.]+)/) };
}

/** Parses probe-truth-order-sensitivity.mjs's Section A summary line
 *  ("false positives on clean text = Y/X scripts") — the real-corpus
 *  recall/false-positive headline this stage exists to answer. */
export function parseTruthExtractionOutput(stdout) {
  const m = /Section A \(real, n=(\d+)\): false positives on clean text = (\d+)\/(\d+) scripts\./.exec(stdout ?? '');
  if (!m) return { totalScripts: null, falsePositiveScripts: null };
  return { totalScripts: Number(m[1]), falsePositiveScripts: Number(m[2]) };
}

// ═══════════════════════════════════════════════════════════════════════
// CLI argument parsing
// ═══════════════════════════════════════════════════════════════════════

export function parseArgs(argv) {
  const out = { only: null, skip: null, reason: null, help: false };
  for (const a of argv) {
    if (a === '--help' || a === '-h') out.help = true;
    else if (a.startsWith('--only=')) out.only = a.slice('--only='.length).split(',').map((s) => s.trim()).filter(Boolean);
    else if (a.startsWith('--skip=')) out.skip = a.slice('--skip='.length).split(',').map((s) => s.trim()).filter(Boolean);
    else if (a.startsWith('--reason=')) out.reason = a.slice('--reason='.length);
    else {
      throw new Error(`Unknown argument: ${a}. See --help.`);
    }
  }
  if (out.only && out.skip) {
    throw new Error('--only and --skip are mutually exclusive — pick one.');
  }
  return out;
}

