/** Spawns a command, streaming stdout/stderr to this process's own streams
 *  live while also buffering them for parsing/receipt purposes. */
function realRunCommand(cmd, args, opts = {}) {
  return new Promise((resolve) => {
    console.log(`\n$ ${[cmd, ...args].join(' ')}`);
    const child = spawn(cmd, args, { cwd: REPO_ROOT, env: { ...process.env, ...(opts.env || {}) } });
    let stdout = '';
    let stderr = '';
    child.stdout.on('data', (d) => { const s = d.toString(); stdout += s; process.stdout.write(s); });
    child.stderr.on('data', (d) => { const s = d.toString(); stderr += s; process.stderr.write(s); });
    child.on('error', (error) => resolve({ ok: false, status: null, stdout, stderr, error }));
    child.on('close', (status) => resolve({ ok: status === 0, status, stdout, stderr, error: null }));
  });
}

function realGitRevParse() {
  try {
    return execFileSync('git', ['rev-parse', 'HEAD'], { cwd: REPO_ROOT, encoding: 'utf-8' }).trim();
  } catch {
    return 'unknown (git rev-parse HEAD failed)';
  }
}

function realReadSplitFile() {
  try {
    return JSON.parse(fs.readFileSync(SPLIT_FILE, 'utf-8'));
  } catch {
    return null;
  }
}

function countFountainFiles(dir) {
  if (!dir) return 0;
  let count = 0;
  const walk = (d) => {
    let entries;
    try {
      entries = fs.readdirSync(d, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      const full = path.join(d, e.name);
      if (e.isDirectory()) walk(full);
      else if (/\.fountain(\.txt)?$/.test(e.name)) count += 1;
    }
  };
  walk(dir);
  return count;
}

