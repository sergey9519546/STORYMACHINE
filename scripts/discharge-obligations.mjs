/** Selects which stage ids should run given --only/--skip, validating that
 *  every referenced id actually exists. Throws on an unknown id. */
/** @param {Stage[]} stages
 *  @param {{ only: string[]|null, skip: string[]|null }} opts
 *  @returns {Stage[]} */
export function selectStages(stages, { only, skip }) {
  const ids = new Set(stages.map((s) => s.id));
  if (only) {
    for (const id of only) if (!ids.has(id)) throw new Error(`Unknown stage id in --only: "${id}". Known ids: ${[...ids].join(', ')}`);
    return stages.filter((s) => only.includes(s.id));
  }
  if (skip) {
    for (const id of skip) if (!ids.has(id)) throw new Error(`Unknown stage id in --skip: "${id}". Known ids: ${[...ids].join(', ')}`);
    return stages.filter((s) => !skip.includes(s.id));
  }
  return stages;
}

/**
 * Runs the full orchestration. Every dependency the real CLI uses (command
 * execution, git SHA lookup, split-file reading, migration check, file
 * existence, current date, output stream) is injectable so tests can drive
 * this with a mock corpus dir and fake command runner. See file header
 * "TESTING NOTE".
 *
 * @param {string[]} argv
 * @param {Record<string, string|undefined>} [env]
 * @param {{
 *   runCommand?: StageCtx['runCommand'],
 *   gitRevParse?: () => string,
 *   readSplitFile?: () => any,
 *   checkMigration?: (splitData: any) => boolean,
 *   fileExists?: (p: string) => boolean,
 *   now?: () => Date,
 *   log?: (...a: any[]) => void,
 *   writeReceiptFile?: (p: string, content: string) => void,
 *   stages?: Stage[],
 * }} [deps]
 * @returns {Promise<{ exitCode: number, results: StageResultRecord[], receipt: string, receiptPath: string }>}
 */
export async function main(argv, env = process.env, deps = {}) {
  const {
    runCommand = realRunCommand,
    gitRevParse = realGitRevParse,
    readSplitFile = realReadSplitFile,
    checkMigration = isMigrationApplied,
    fileExists = (p) => fs.existsSync(p),
    now = () => new Date(),
    log = (...a) => console.log(...a),
    writeReceiptFile = (p, content) => fs.writeFileSync(p, content, 'utf-8'),
    stages = STAGES,
  } = deps;

  let args;
  try {
    args = parseArgs(argv);
  } catch (err) {
    log(err.message);
    return { exitCode: 2, results: [], receipt: '', receiptPath: '' };
  }
  if (args.help) {
    log(USAGE);
    return { exitCode: 0, results: [], receipt: '', receiptPath: '' };
  }

  const envCheck = checkEnvContract(env);
  if (!envCheck.ok) {
    log(envCheck.message);
    return { exitCode: 1, results: [], receipt: '', receiptPath: '' };
  }

  let selected;
  try {
    selected = selectStages(stages, { only: args.only, skip: args.skip });
  } catch (err) {
    log(err.message);
    return { exitCode: 2, results: [], receipt: '', receiptPath: '' };
  }

  const { realScriptCorpusDir, corpusDir } = resolveCorpusDirs(env);
  const ctx = { realScriptCorpusDir, corpusDir, runCommand, readSplitFile, checkMigration, fileExists };

  log(`discharge-obligations: running ${selected.length}/${stages.length} stage(s): ${selected.map((s) => s.id).join(', ')}`);

  const results = [];
  for (const stage of selected) {
    log(`\n${'═'.repeat(78)}\nSTAGE: ${stage.id} — ${stage.label}\n${'═'.repeat(78)}`);
    let outcome;
    try {
      outcome = await stage.run(ctx);
    } catch (err) {
      // A thrown guard (e.g. assertSafePartition) or unexpected error is
      // recorded as a failed stage, never a crash of the whole run — "the
      // run continues past a failed stage" applies to guard failures too.
      outcome = { ok: false, skipped: false, commands: [], notes: [`Stage threw: ${err.message}`], measured: {} };
    }
    results.push({ id: stage.id, label: stage.label, optional: !!stage.optional, ...outcome });
    log(`STAGE RESULT: ${stage.id} — ${outcome.skipped ? 'SKIPPED' : outcome.ok ? 'OK' : 'FAILED'}`);
  }

  log(`\n${'═'.repeat(78)}\nSUMMARY\n${'═'.repeat(78)}`);
  for (const r of results) {
    log(`  ${r.skipped ? 'SKIP ' : r.ok ? 'OK   ' : 'FAIL '} ${r.id}${r.optional ? ' (optional)' : ''}`);
  }
  const hardFailures = results.filter((r) => !r.skipped && !r.ok && !r.optional);
  const softFailures = results.filter((r) => !r.skipped && !r.ok && r.optional);
  if (softFailures.length > 0) {
    log(`\n${softFailures.length} optional stage(s) failed (not blocking): ${softFailures.map((r) => r.id).join(', ')}`);
  }

  const date = now().toISOString().slice(0, 10);
  const sha = gitRevParse();
  const fountainCount = countFountainFiles(realScriptCorpusDir || corpusDir);
  const splitData = readSplitFile();
  const testSetHash = splitData?.testSetHash ?? 'unknown';
  const corpusFingerprint = `${fountainCount} fountain file(s) found under the configured corpus dir; scripts/output/corpus-split.json testSetHash=${testSetHash}`;
  const reason = args.reason || 'scripts/discharge-obligations.mjs orchestrated run — discharge accumulated maintainer-machine obligations';

  const receipt = buildReceipt({ results, sha, date, corpusFingerprint, reason });

  log(`\n${'═'.repeat(78)}\nPASTE-READY ${RECEIPTS_LEDGER_REL} ENTRY (review + fill in the attestation before pasting)\n${'═'.repeat(78)}\n`);
  log(receipt);

  const receiptPath = path.join(os.tmpdir(), `storymachine-pending-receipt-${date}-${Date.now()}.md`);
  writeReceiptFile(receiptPath, receipt);
  log(`\n(Also written to ${receiptPath} — NOT under scripts/output/ and NOT auto-appended to the ledger. Paste it into ${RECEIPTS_LEDGER_REL} yourself, above "## 3. Entry template", after filling in the attestation.)`);

  return { exitCode: hardFailures.length > 0 ? 1 : 0, results, receipt, receiptPath };
}

