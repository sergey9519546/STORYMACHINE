// ═══════════════════════════════════════════════════════════════════════
// Receipt rendering — follows MEASUREMENT_RECEIPTS.md §3's template exactly,
// with extra bullets appended for the per-stage detail the fixed template
// doesn't have fields for (matching the ledger's own precedent — the
// 2026-08-04 entry already extends the template with a "Blast radius"
// bullet when the fixed fields aren't enough).
// ═══════════════════════════════════════════════════════════════════════

/** @param {{ results: StageResultRecord[], sha: string, date: string, corpusFingerprint: string, reason: string }} args
 *  @returns {string} */
export function buildReceipt({ results, sha, date, corpusFingerprint, reason }) {
  const byId = Object.fromEntries(results.map((r) => [r.id, r]));
  const lines = [];
  lines.push(`### ${date} — ${reason}`);
  lines.push('');
  lines.push(`- **Date:** ${date}`);
  lines.push(`- **Git SHA:** \`${sha}\``);
  lines.push('- **Command:** `npm run discharge-obligations` (scripts/discharge-obligations.mjs), which ran:');
  for (const r of results) {
    if (r.commands.length === 0) continue;
    for (const c of r.commands) lines.push(`  - \`${c}\``);
  }
  const measureReal = byId['measure-real'];
  const auc24 = measureReal && !measureReal.skipped && measureReal.ok
    ? `shuffle-drop AUC ${measureReal.measured.shuffleDropAuc ?? 'see stage log'}, act-swap AUC ${measureReal.measured.actSwapAuc ?? 'see stage log'}`
    : (measureReal?.skipped ? 'not run — stage skipped, see below' : 'not measured — stage failed, see stage log');
  lines.push(`- **Measured AUC-24:** ${auc24}`);

  const aucSplit = byId['auc-split-unwired-flags'];
  const flagLines = [];
  if (aucSplit && !aucSplit.skipped) {
    for (const [key, val] of Object.entries(aucSplit.measured)) {
      flagLines.push(`${key} ALL POOLED AUC=${val ?? 'see stage log'}`);
    }
  }
  lines.push(`- **Flag-run AUCs:** ${flagLines.length > 0 ? flagLines.join('; ') : 'not run — stage skipped, see below'}`);
  lines.push(`- **Corpus fingerprint:** ${corpusFingerprint}`);
  lines.push('- **Runner attestation:** "<REPLACE ME — name/role> measured this locally on ' + date + ', <machine/session context>." — NOT auto-signed; fill this in before pasting, per MEASUREMENT_RECEIPTS.md\'s rule that the entry\'s honesty is a human/reviewer responsibility.');
  lines.push('');
  lines.push('_Extra detail beyond the §3 template (per-stage), for context:_');
  for (const r of results) {
    lines.push('');
    lines.push(`**${r.id}** — ${r.skipped ? 'SKIPPED' : r.ok ? 'OK' : 'FAILED'}`);
    for (const n of r.notes) lines.push(`  - ${n}`);
  }
  return lines.join('\n');
}

