#!/usr/bin/env node
// DISCHARGE-OBLIGATIONS — one command that runs every maintainer-machine
// obligation that can only be discharged where the private 761-script
// corpus lives, and prints a ready-to-paste MEASUREMENT_RECEIPTS.md entry.
//
// ── WHY THIS EXISTS ──────────────────────────────────────────────────────
// These obligations are scattered across docs and each has its own env var,
// flag, and output shape:
//   1. `npm run measure-real` — the AUC-24 ratchet
//      (tests/core/real-script-corpus.test.ts's statistic, printed by
//      scripts/measure-real-script-discrimination.ts) — discharges the
//      2026-08-04 normalizer entry's open re-measurement obligation in
//      docs/p1-benchmark/MEASUREMENT_RECEIPTS.md. That script prints numbers
//      but writes NOTHING to disk (verified by reading it: no writeFileSync
//      call exists in it at all) — the artifact the ledger entry actually
//      calls "known stale by 0.1" is scripts/output/real-corpus-scores.csv,
//      which is regenerated by a DIFFERENT script, scripts/probe-real-
//      corpus.mjs (over data/screenplays/, guarded against silently
//      shrinking the committed evidence file — see scripts/lib/output-
//      guard.mjs). This stage runs both.
//   2. `scripts/measure-auc-split.mjs` with each currently-unwired signal
//      flag (question-latency deduction, reversal detection, agency
//      signal), on train+val ONLY — the test partition is evaluate-once,
//      never for iteration (see MEASUREMENT_RUNBOOK.md §2.3, "ONCE, Final
//      Evaluation Only"), so this orchestrator refuses to construct a
//      --partition=test invocation for these flags, structurally
//      (assertSafePartition below; there is no CLI surface here that can
//      even pass "test" through).
//   3. Truth-extraction recall on real material — does detectTruthContra-
//      dictions() (server/nvm/analyze/truth-extraction.ts) fire on real
//      thrillers at all? scripts/probe-truth-order-sensitivity.mjs already
//      wires REAL_SCRIPT_CORPUS_DIR for exactly this ("RECALL MODE").
//   4. The corpus de-id migration (scripts/migrate-corpus-ids.mjs), if not
//      already applied — detected by inspecting the CURRENT
//      scripts/output/corpus-split.json's schema (every entry carrying
//      `id` + `contentHash` means it's migrated; this is the exact test
//      scripts/verify-corpus-layout.mjs itself uses), never by trusting a
//      flag or a comment.
//   5. scripts/rebuild-experiment.mjs — feature-detected. It does not exist
//      in this tree as of writing; if a later change adds it, this
//      orchestrator picks it up automatically as an optional stage with no
//      further wiring required.
//
// ── ENV CONTRACT ─────────────────────────────────────────────────────────
// At least one of REAL_SCRIPT_CORPUS_DIR / CORPUS_DIR must be set, or the
// script fails fast before running anything (there is nothing to discharge
// without local corpus access). Whichever one IS set is used as a fallback
// for the other's stages too (same physical corpus, two historical env-var
// names — see resolveCorpusDirs) so a maintainer only has to set one.
//
// ── OUTPUT CONTRACT ──────────────────────────────────────────────────────
// This script NEVER writes to docs/p1-benchmark/MEASUREMENT_RECEIPTS.md and
// NEVER writes scripts/output/pending-receipt-<date>.md (scripts/output/
// holds committed evidence, not scratch drafts — see scripts/lib/output-
// guard.mjs's header for the incident that rule exists to prevent). The
// rendered receipt block goes to stdout AND to a file under os.tmpdir();
// the maintainer reviews it and pastes it into the ledger by hand — that
// deliberate human step is the entire point of the ledger (see
// MEASUREMENT_RECEIPTS.md's own "What this ledger is NOT" section).
//
// ── RUN ──────────────────────────────────────────────────────────────────
//   REAL_SCRIPT_CORPUS_DIR=/path/to/corpus npm run discharge-obligations
//   REAL_SCRIPT_CORPUS_DIR=/path/to/corpus node scripts/discharge-obligations.mjs --only=measure-real
//   REAL_SCRIPT_CORPUS_DIR=/path/to/corpus node scripts/discharge-obligations.mjs --skip=corpus-migration
//
// ── TESTING NOTE ─────────────────────────────────────────────────────────
// Every stateful operation this module performs (spawning a command,
// resolving `git rev-parse HEAD`, checking whether the migration is already
// applied) is exposed as an injectable dependency to `main()` so
// tests/scripts/discharge-obligations.test.ts can exercise real
// orchestration logic (sequencing, env gating, --only/--skip, the
// test-partition guard, receipt rendering) against a MOCK corpus directory
// without spawning the real multi-second measurement subprocesses. That
// validates PIPELINE MECHANICS, not corpus discrimination values — see the
// test file's own header for the same caveat stated at the point of use.

